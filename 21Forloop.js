//while loop

let counter = 0; //Initialization
while (counter < 100) { //condition check
  console.log(`${counter + 1}`);
  counter = counter + 1; //update
}
console.log("out of the loop");


//for loop

for(let c=0; c<100; c++){
    console.log(`${c+1}`);
}
console.log("out of the for loop");

//let c=0 -> run only once it is initialization
//c<100  -> condition 1st it run then 
//c++ -> run 2nd then 
//3rd body will run this continus cycle run one by one
